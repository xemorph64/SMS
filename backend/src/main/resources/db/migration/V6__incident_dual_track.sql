-- Dual-track incident management: first-class incidents with parallel
-- Incident-Response and Digital-Forensics tracks, converged by an audit gate.
--
-- One incident per (capture_id, stream_id) that carried a critical or high
-- finding. The status column is the parent state machine:
--
--   DETECTED ──triage──> DISMISSED
--      └────triage───> ESCALATED ──(IR RECOVERED + DF REPORT_SUBMITTED)──> AWAITING_AUDIT
--                          ^                                                  │
--                          └── REJECTED_IR / REJECTED_FORENSICS ──────────────┘
--                                                               APPROVED ──> VERIFIED_CLOSED
--
-- The ir_track and df_track rows are created by triage (ESCALATED only) and are
-- 1:1 with the incident. Every verdict leaves a permanent audit_review row.
--
-- Plain portable SQL throughout, matching V1-V5: identity columns, VARCHAR
-- status enums enforced by the application layer, TIMESTAMP in UTC (the JVM
-- test suite runs with -Duser.timezone=UTC and Instant is stored UTC).

CREATE TABLE incident (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capture_id              BIGINT       NOT NULL,
    stream_id               VARCHAR(100) NOT NULL,
    status                  VARCHAR(32)  NOT NULL DEFAULT 'DETECTED',
    escalated_at            TIMESTAMP,
    cert_in_clock_deadline  TIMESTAMP,
    snapshot_hash           VARCHAR(64),
    dismissed_by            VARCHAR(255),
    dismissal_reason        VARCHAR(2000),
    updated_by              VARCHAR(255),
    updated_at              TIMESTAMP    NOT NULL DEFAULT NOW(),
    UNIQUE (capture_id, stream_id)
);

CREATE INDEX idx_incident_status   ON incident (status);
CREATE INDEX idx_incident_capture  ON incident (capture_id);

CREATE TABLE ir_track (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id       BIGINT      NOT NULL REFERENCES incident (id) ON DELETE CASCADE,
    ir_status         VARCHAR(32) NOT NULL DEFAULT 'INVESTIGATING',
    remediation_notes VARCHAR(4000),
    assigned_to       BIGINT,
    updated_at        TIMESTAMP   NOT NULL DEFAULT NOW(),
    UNIQUE (incident_id)
);

CREATE TABLE df_track (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id        BIGINT      NOT NULL REFERENCES incident (id) ON DELETE CASCADE,
    df_status          VARCHAR(32) NOT NULL DEFAULT 'EVIDENCE_LOCKED',
    evidence_lock_hash VARCHAR(64),
    forensic_report    TEXT,
    assigned_to        BIGINT,
    updated_at         TIMESTAMP   NOT NULL DEFAULT NOW(),
    UNIQUE (incident_id)
);

CREATE TABLE audit_review (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id      BIGINT      NOT NULL REFERENCES incident (id) ON DELETE CASCADE,
    auditor_id       BIGINT,
    verdict          VARCHAR(32) NOT NULL,
    rejection_reason VARCHAR(2000),
    reviewed_at      TIMESTAMP   NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_audit_incident ON audit_review (incident_id);

-- ---------------------------------------------------------------- backfill ----
-- Existing captures already analysed: every session that carried a critical or
-- high finding becomes a DETECTED incident, so the SOC triage inbox lights up
-- against data that predates this migration. stream_id keeps the existing
-- convention used across the app (findings_status rows and every dashboard
-- build their keys by joining capture id, a dash, then stream id): the bare
-- stream number, not a composite. No dollar-brace sequences in this file —
-- Flyway would read them as placeholders.

INSERT INTO incident (capture_id, stream_id, status, updated_at)
SELECT DISTINCT ms.capture_id,
       CAST(ms.stream_index AS VARCHAR(100)),
       'DETECTED',
       NOW()
FROM mail_session ms
JOIN finding f ON f.session_id = ms.id
WHERE f.severity IN ('critical', 'high');
